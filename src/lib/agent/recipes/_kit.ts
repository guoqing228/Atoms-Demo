import type { FileMap, PlanFeature, Theme } from "../../types";
import { themeCssVars } from "../themes";

/**
 * Shared kit for every mock-agent recipe.
 *
 * Every generated app is a tiny 3-file project (index.html / styles.css /
 * app.js) so the workspace can show a real file tree and per-file diffs, and
 * the preview panel can inline the files into a single sandboxed document.
 */

export interface RecipeContext {
  prompt: string;
  theme: Theme;
  /** previous files when the user iterates on an existing app */
  prev?: FileMap | null;
}

export interface RecipeOutput {
  /** product name shown in the workspace header */
  name: string;
  tagline: string;
  /** one paragraph: what the app does */
  summary: string;
  features: PlanFeature[];
  /** inner HTML of <body> */
  body: string;
  /** app-specific CSS, appended after the shared reset */
  css: string;
  /** app-specific JS (classic script, wrapped in an IIFE by the kit) */
  js: string;
}

export interface Recipe {
  id: string;
  label: string;
  /** lower-case keywords matched against the user prompt */
  keywords: string[];
  build(ctx: RecipeContext): RecipeOutput;
}

const RESET_CSS = `*,*::before,*::after{box-sizing:border-box}
html,body{margin:0;padding:0}
body{background:var(--bg);color:var(--text);font-family:var(--font);min-height:100vh;-webkit-font-smoothing:antialiased}
button,input,select,textarea{font:inherit;color:inherit}
button{cursor:pointer;border:none;background:none}
a{color:var(--accent)}
h1,h2,h3,h4,p{margin:0}
ul,ol{margin:0;padding:0;list-style:none}
::selection{background:color-mix(in srgb,var(--accent) 30%,transparent)}
@media (prefers-reduced-motion: reduce){*,*::before,*::after{transition-duration:.01ms!important;animation-duration:.01ms!important;animation-iteration-count:1!important}}`;

const HTML_TEMPLATE = (title: string, body: string, dark: boolean) => `<!DOCTYPE html>
<html lang="zh-CN"${dark ? ' data-theme="dark"' : ""}>
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${title}</title>
  <link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect width='32' height='32' rx='7' fill='%23ffffff'/%3E%3Cpath d='M16 7.6c.6 3.7 2.5 5.6 6.2 6.2-3.7.6-5.6 2.5-6.2 6.2-.6-3.7-2.5-5.6-6.2-6.2 3.7-.6 5.6-2.5 6.2-6.2Z' fill='%232e5e4c'/%3E%3C/svg%3E" />
  <link rel="stylesheet" href="styles.css" />
</head>
<body>
${body.trim()}
  <script src="app.js"></script>
</body>
</html>`;

/**
 * Turn a recipe output into the 3-file project the workspace stores.
 * `app.js` is wrapped in an IIFE so recipes never leak globals by accident.
 */
export function assembleFiles(out: RecipeOutput, theme: Theme): FileMap {
  const title = out.name;
  return {
    "index.html": HTML_TEMPLATE(title, out.body, theme.mode === "dark"),
    "styles.css": `${RESET_CSS}\n\n${themeCssVars(theme)}\n\n${out.css.trim()}\n`,
    "app.js": `/* ${title} — generated by VibeForge mock agent */\n(function () {\n"use strict";\n${out.js.trim()}\n})();\n`,
  };
}

/** Pretty plan builder so recipes stay short. */
export function planOf(
  name: string,
  tagline: string,
  summary: string,
  features: PlanFeature[],
  stack: string[],
) {
  return { name, tagline, summary, stack, features };
}

/** Escape user text before interpolating into generated HTML. */
export function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/** Small helper: format a byte count for the plan/feature copy. */
export function humanBytes(n: number): string {
  if (n < 1024) return `${n} B`;
  return `${(n / 1024).toFixed(1)} KB`;
}
